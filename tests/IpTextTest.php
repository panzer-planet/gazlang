    public function test_it_writes_each_address_as_rfc_5952_says()
    {
        $dir = sys_get_temp_dir().'/gazlang_iptext_'.getmypid();
        @mkdir($dir);
        try {
            $root = dirname(__DIR__);
            exec(sprintf('cc -std=c11 -D_DEFAULT_SOURCE -I %s -o %s %s %s 2>&1', escapeshellarg($root.'/vm'), escapeshellarg($dir.'/check'), escapeshellarg($root.'/tests/fixtures/ip_text_check.c'), escapeshellarg($root.'/vm/ipaddr.c')), $output, $code);
            $this->assertSame(0, $code, implode("\n", $output));

            $arguments = implode(' ', array_map(fn ($row) => $row[1].':'.$row[0], self::ADDRESSES));
            $lines = explode("\n", trim((string) shell_exec(escapeshellarg($dir.'/check').' '.$arguments)));
            $this->assertCount(count(self::ADDRESSES), $lines);
            foreach (self::ADDRESSES as $i => [$hex, $family, $expected]) {
                $this->assertSame($expected, $lines[$i], "IPv{$family} {$hex}");
            }
        } finally {
            exec('rm -rf '.escapeshellarg($dir));
        }
    }
